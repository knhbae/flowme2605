function rowsFromTitles(titles, prefix, group = null) {
  return titles.map((entry, index) => {
    if (typeof entry === "string") {
      return {
        sourceRowId: `${prefix}-${String(index + 1).padStart(2, "0")}`,
        title: entry,
        group,
      };
    }
    return {
      sourceRowId: `${prefix}-${String(index + 1).padStart(2, "0")}`,
      ...entry,
    };
  });
}

