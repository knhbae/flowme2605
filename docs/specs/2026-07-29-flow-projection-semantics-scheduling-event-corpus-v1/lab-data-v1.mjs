const OBSERVED_AT = '2026-07-29';

const rows = (fixtureId, values) =>
  values.map((value, index) => ({
    sourceRowId: `${fixtureId}-row-${String(index + 1).padStart(2, '0')}`,
    order: index,
    ...value,
  }));

const item = (
  fixtureId,
  number,
  title,
  sourceRowNumbers,
  {
    intent = 'act',
    stepId = `${fixtureId}-step-1`,
    description = '',
    completion = 'check',
    dependsOn = [],
    temporalIntent = 'no_schedule',
    schedule = null,
  } = {},
) => ({
  itemId: `${fixtureId}-item-${String(number).padStart(2, '0')}`,
  stepId,
  title,
  description,
  intent,
  order: number - 1,
  completion: {
    mode: completion,
    doneWhen:
      completion === 'consume'
        ? `${title} 자료를 확인하고 진도 상태를 남겼다.`
        : `${title} 결과를 확인하고 상태를 남겼다.`,
  },
  temporalIntent,
  schedule,
  dependsOnItemIds: dependsOn.map(
    (dependency) =>
      `${fixtureId}-item-${String(dependency).padStart(2, '0')}`,
  ),
  sourceRowIds: sourceRowNumbers.map(
    (sourceRowNumber) =>
      `${fixtureId}-row-${String(sourceRowNumber).padStart(2, '0')}`,
  ),
});

const makeStep = (fixtureId, title, items, order = 0) => ({
  stepId: `${fixtureId}-step-${order + 1}`,
  title,
  order,
  itemIds: items.map((entry) => entry.itemId),
});

const baseFixture = ({
  fixtureId,
  fixtureGroup,
  fixtureKind,
  title,
  provider,
  url,
  locale,
  sourceShape,
  executionPattern,
  primaryProjection,
  userJob,
  sourceRows,
  items = [],
  steps = null,
  eventModel = null,
  sourceSchedulePresent = false,
  pacingEligible = false,
  sourceNotes = [],
}) => ({
  fixtureId,
  fixtureGroup,
  fixtureKind,
  title,
  provider,
  url,
  canonicalUrl: url,
  locale,
  observedAt: OBSERVED_AT,
  accessStatus: 'public_html_open',
  evidenceMethod: 'direct_page_inspection',
  sourceShape,
  executionPattern,
  primaryProjection,
  userJob,
  sourceRows: rows(fixtureId, sourceRows),
  steps: steps ?? (items.length ? [makeStep(fixtureId, title, items)] : []),
  items,
  eventModel,
  sourceSchedulePresent,
  pacingEligible,
  sourceNotes,
});

