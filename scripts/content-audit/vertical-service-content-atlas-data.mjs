function dataFields({ explicit = [], prose = [], creator = [], inferred = [], external = [] } = {}) {
  const fields = Object.fromEntries(fieldKeys.map((key) => [key, 'absent']));
  for (const key of prose) fields[key] = 'present_in_prose_or_media';
  for (const key of creator) fields[key] = 'creator_judgment';
  for (const key of inferred) fields[key] = 'flowme_inference_required';
  for (const key of external) fields[key] = 'external_live_data';
  for (const key of explicit) fields[key] = 'explicit_structured_or_labeled';
  return fields;
}

