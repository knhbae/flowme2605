function materializeService(spec) {
  if (spec.scoreValues.length !== scoreDimensions.length) {
    throw new Error(`${spec.id}: expected ${scoreDimensions.length} scores`);
  }
  const scores = Object.fromEntries(scoreDimensions.map((dimension, index) => {
    const score = spec.scoreValues[index];
    return [dimension, { score, comment: scoreComments[dimension](spec, score) }];
  }));
  const evidenceLevels = [...new Set(spec.evidenceSources.map((item) => {
    if (item.type === 'app_store') return 'app_store_verified';
    if (item.type === 'support_doc') return 'support_doc_verified';
    return 'public_web_verified';
  }))];
  return {
    ...spec,
    scores,
    evidenceLevels,
    userCommunicationEvidence: communicationEvidenceById[spec.id],
    businessEvidenceRecord: {
      observed: spec.businessEvidence,
      internalAssessment: spec.businessNote,
      unknown: '실제 제휴 의사·전환율·매출 기여는 확인하지 않았으며 사업 가설로 승격하지 않는다.',
    },
    observationInferenceBoundary: {
      observedFacts: spec.evidenceSources.map((item) => item.claim),
      flowmeInference: spec.flowmeDelta,
      unknowns: [
        '로그인 후 개인화 결과',
        '실제 사용자의 장기 완주율',
        '제작자·서비스의 제휴 의사',
      ],
    },
    verificationBoundary: '공개 웹·공식 지원 문서·앱스토어 설명만 확인했다. 로그인 후 개인화 결과는 in_app_verified가 아니다.',
    compression: {
      userMoment: spec.userMoment,
      naturalArtifact: spec.generatedArtifact,
      minimumAnchor: spec.initialInputs.filter((item) => item.required).map((item) => item.name),
      stage0Behavior: spec.stage0Behavior,
      serviceRelationship: spec.serviceRelationship,
      contentDiscoveryOpportunity: spec.opportunityId,
      doNotBuildBoundary: spec.doNotBuild.join(' / '),
      finalDecision: spec.finalDecision,
    },
  };
}

